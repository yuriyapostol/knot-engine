import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
import { existsSync } from 'node:fs'
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || (existsSync('/usr/bin/google-chrome') ? '/usr/bin/google-chrome' : chromium.executablePath()), headless: true, args: ['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-webgl'] })
try {
 const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } })
 const errors = []
 page.on('pageerror',e=>errors.push(e.message))
 await page.goto((process.env.SITE_TEST_URL || 'http://127.0.0.1:5173')+'/v1/guide/getting-started.html')
 assert.equal(await page.locator('html').getAttribute('lang'),'en')
 await page.locator('a[hreflang="uk"]').click()
 assert.match(page.url(),/\/v1\/guide\/getting-started\.uk\.html$/)
 assert.equal(await page.locator('html').getAttribute('lang'),'uk')
 assert.equal(await page.locator('iframe').count(),0)
 assert.equal(await page.locator('main').count(),1, 'The demo must not add a nested main landmark')
 const demo = page.locator('.knot-engine-v1-demo')
 await demo.scrollIntoViewIfNeeded()
 await demo.locator('.knot-engine-v1-viewer[data-state="ready"]').waitFor({timeout:30000})
 assert.equal(await demo.getAttribute('lang'),'uk')
 const editor = demo.locator('textarea')
 assert.ok(await editor.isVisible())
 assert.equal(await page.locator('header .status').count(),0)
 const palette = () => demo.evaluate(root => {
   const css = getComputedStyle(root), host = getComputedStyle(document.documentElement)
   const panel = getComputedStyle(root.querySelector('.knot-engine-v1-demo__panel'))
   const input = getComputedStyle(root.querySelector('textarea'))
   const viewer = getComputedStyle(root.querySelector('.knot-engine-v1-viewer'))
   return { background: css.backgroundColor, border: css.borderTopWidth, padding: css.padding, margin: css.margin,
     panelBackground: panel.backgroundColor, panelBorder: panel.borderTopWidth, panelPadding: panel.padding,
     color: css.color, hostColor: host.color, surface: host.getPropertyValue('--subtle').trim(),
     inputColor: input.color, viewerBackground: viewer.backgroundColor, inputBackground: input.backgroundColor }
 })
 const assertPalette = async () => {
   const colors = await palette()
   assert.equal(colors.background,'rgba(0, 0, 0, 0)')
   assert.equal(colors.border,'0px'); assert.equal(colors.padding,'0px'); assert.equal(colors.margin,'0px')
   assert.equal(colors.panelBackground,'rgba(0, 0, 0, 0)'); assert.equal(colors.panelBorder,'0px'); assert.equal(colors.panelPadding,'0px')
   assert.equal(colors.color,colors.hostColor); assert.equal(colors.inputColor,colors.hostColor)
   assert.equal(colors.viewerBackground,colors.inputBackground)
 }
 await assertPalette()
 await demo.screenshot({path:'/tmp/knot-demo-light.png'})
 const editedCode = (await editor.inputValue()) + '\n '
 await editor.fill(editedCode)
 const initialTheme = await page.locator('html').getAttribute('data-theme')
 const initialPalette = await palette()
 await page.locator('.theme-toggle').click()
 const changedTheme = initialTheme === 'dark' ? 'light' : 'dark'
 await page.locator(`.knot-engine-v1-demo[data-theme="${changedTheme}"]`).waitFor()
 assert.equal(await editor.inputValue(),editedCode)
 await assertPalette()
 assert.notEqual((await palette()).inputBackground,initialPalette.inputBackground)
 // Inline editing still retains valid input, supports local files and exports.
 await editor.fill('{')
 await demo.locator('[role="alert"]').waitFor()
 assert.equal(await demo.locator('.knot-engine-v1-viewer').getAttribute('data-state'),'ready')
 await editor.fill(editedCode)
 await demo.locator('[role="alert"]').waitFor({state:'detached'})
 await demo.locator('.knot-engine-v1-viewer[data-state="ready"]').waitFor()
 const imported = JSON.parse(editedCode)
 imported.id = 'inline-imported'
 await demo.locator('input[type="file"]').setInputFiles({ name:'asset.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(imported)) })
 await demo.locator('.knot-engine-v1-viewer[data-state="ready"][aria-label="inline-imported"]').waitFor()
 assert.equal(await demo.locator('.knot-engine-v1-demo__representation-select').inputValue(),imported.representations[0].id)
 assert.equal(await demo.locator('[role="alert"]').count(),0)
 await demo.locator('.knot-engine-v1-viewer[data-state="ready"]').waitFor()
 const [json] = await Promise.all([page.waitForEvent('download'),demo.getByRole('button',{name:'Зберегти в файл',exact:true}).click()])
 assert.equal(json.suggestedFilename(),'knot-asset.json')
 const [png] = await Promise.all([page.waitForEvent('download'),demo.getByRole('button',{name:'Експорт в PNG',exact:true}).click()])
 assert.equal(png.suggestedFilename(),'knot-current.png')
 await page.screenshot({path:'/tmp/knot-site-desktop.png',fullPage:true})
 await demo.screenshot({path:'/tmp/knot-demo-desktop.png'})
 await page.reload()
 assert.equal(await page.locator('html').getAttribute('data-theme'),changedTheme)
 await demo.scrollIntoViewIfNeeded()
 await page.locator(`.knot-engine-v1-demo[data-theme="${changedTheme}"]`).waitFor()
 await page.locator('a[hreflang="en"]').click()
 assert.match(page.url(),/\/v1\/guide\/getting-started\.html$/)
 await demo.scrollIntoViewIfNeeded()
 await page.locator('.knot-engine-v1-demo[lang="en"]').waitFor()
 await page.locator(`.knot-engine-v1-demo[data-theme="${changedTheme}"]`).waitFor()
 await demo.locator('.knot-engine-v1-viewer[data-state="ready"]').waitFor()
 await page.setViewportSize({width:390,height:844})
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true)
 assert.equal(await demo.locator('.knot-engine-v1-demo__layout').evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' ').length),1)
 await page.screenshot({path:'/tmp/knot-site-mobile.png',fullPage:true})
 await demo.screenshot({path:'/tmp/knot-demo-mobile.png'})
 // Multiple mount points share the document theme but keep editor/model state independent.
 const multiple = await browser.newPage({viewport:{width:1280,height:1000}})
 multiple.on('pageerror',error=>errors.push(error.message))
 await multiple.route('**/v1/guide/getting-started.html',async route=>{
   const response = await route.fetch()
   const body = (await response.text()).replace('</main>','<div data-knot-engine-demo="v1"></div></main>')
   await route.fulfill({response,body})
 })
 await multiple.goto((process.env.SITE_TEST_URL || 'http://127.0.0.1:5173')+'/v1/guide/getting-started.html')
 const instances = multiple.locator('.knot-engine-v1-demo')
 assert.equal(await instances.count(),2)
 for (const instance of await instances.all()) {
   await instance.scrollIntoViewIfNeeded()
   await instance.locator('.knot-engine-v1-viewer[data-state="ready"]').waitFor()
 }
 await instances.first().scrollIntoViewIfNeeded()
 await instances.first().locator('.knot-engine-v1-demo__model-select select').selectOption('loop')
 await instances.first().locator('.knot-engine-v1-viewer[data-state="ready"][aria-label="twisted-loop"]').waitFor()
 assert.equal(await instances.last().locator('.knot-engine-v1-demo__model-select select').inputValue(),'overhand')
 assert.equal(JSON.parse(await instances.last().locator('textarea').inputValue()).id,'overhand')
 await multiple.close()
 assert.deepEqual(errors,[])
 console.log('Site browser checks passed: inline demo, theme/language inheritance, transparent containers, matching palette, editing, import/download, PNG, mobile layout and independent instances.')
} finally { await browser.close() }
